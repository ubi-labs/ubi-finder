import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createClient } from '@supabase/supabase-js';
import { getLocalAdminClient } from '../acceptance/support/local-supabase.js';
const admin = getLocalAdminClient();
const anon = createClient(process.env.VITE_SUPABASE_URL, process.env.VITE_SUPABASE_ANON_KEY);
const guest = `test:guest:${randomUUID().replaceAll('-', '').repeat(2)}`;
const checked = async (query) => { const result = await query; if (result.error) throw result.error; return result.data; };
const reserve = (amount) => checked(admin.rpc('reserve_donation_checkout', { p_donor_key: guest, p_user_id: null, p_amount_cents: amount, p_livemode: false }));
const fulfill = (session, event, amount = 500) => admin.rpc('fulfill_stripe_donation', { p_event_id: event, p_session_id: session, p_payment_intent_id: `pi_${session}`, p_amount_cents: amount, p_livemode: false, p_receipt_url: 'https://pay.stripe.com/receipts/fixture' });
const sessions = [];
const cryptoIds = [];
let testUser;
try {
  const id = await reserve(500);
  const session = `cs_test_${randomUUID().replaceAll('-', '')}`;
  sessions.push(session);
  await checked(admin.from('donation_checkouts').update({ stripe_session_id: session }).eq('id', id));
  const results = await Promise.all(Array.from({ length: 12 }, (_, i) => fulfill(session, `evt_${session}_${i % 3}`)));
  assert.equal(results.filter((r) => r.data === true).length, 1);
  for (const result of results) assert.equal(result.error, null);
  assert.equal((await checked(admin.from('supporter_accounts').select('total_cents').eq('donor_key', guest).single())).total_cents, 500);
  assert.equal((await checked(admin.from('donations').select('*').eq('stripe_session_id', session))).length, 1);
  const secondId = await reserve(1000);
  const secondSession = `cs_test_${randomUUID().replaceAll('-', '')}`;
  sessions.push(secondSession);
  await checked(admin.from('donation_checkouts').update({ stripe_session_id: secondSession }).eq('id', secondId));
  assert.ok((await fulfill(secondSession, `evt_bad_${secondSession}`, 500)).error);
  assert.equal((await checked(admin.from('stripe_payment_events').select('*').eq('event_id', `evt_bad_${secondSession}`))).length, 0);
  assert.equal((await fulfill(secondSession, `evt_good_${secondSession}`, 1000)).data, true);
  assert.equal((await checked(admin.from('supporter_accounts').select('total_cents').eq('donor_key', guest).single())).total_cents, 1500);
  assert.ok((await anon.rpc('fulfill_stripe_donation', { p_event_id: 'forged', p_session_id: session, p_payment_intent_id: 'pi_forged', p_amount_cents: 500, p_livemode: false, p_receipt_url: null })).error);
  assert.ok((await anon.from('donations').insert({ amount_usd: 999, status: 'completed' })).error);
  assert.ok((await anon.from('user_usage_points').insert({ ip_hash: 'forged', has_donated: true, total_donated_usd: 999 })).error);
  assert.ok((await anon.from('supporter_accounts').select('*')).error);
  const usage = await checked(admin.from('user_usage_points').select('has_donated,total_donated_usd').eq('ip_hash', guest));
  assert.deepEqual(usage, []);
  const password = randomUUID() + 'Aa1!';
  const created = await admin.auth.admin.createUser({ email: `donation-${randomUUID()}@example.test`, password, email_confirm: true });
  if (created.error) throw created.error;
  testUser = created.data.user;
  const accountKey = `test:user:${testUser.id}`;
  const submit = (ownerKey, userId, hash) => admin.rpc('submit_crypto_donation', { p_donor_key: ownerKey, p_user_id: userId, p_amount_cents: 2500, p_livemode: false, p_chain: 'ethereum', p_transaction_hash: hash, p_donor_name: 'Confidential Supporter', p_public_recognition: true });
  const hash = '0x' + randomUUID().replaceAll('-', '').repeat(2);
  const cryptoId = await checked(submit(accountKey, testUser.id, hash));
  cryptoIds.push(cryptoId);
  const record = await checked(admin.from('support_donations').select('*').eq('id', cryptoId).single());
  assert.equal(record.donor_name, 'Confidential Supporter');
  assert.equal(record.public_recognition, true);
  assert.equal(record.review_status, 'pending_review');
  assert.ok(Math.abs(Date.parse(record.review_due_at) - Date.now() - 7 * 86400000) < 10000);
  assert.equal((await checked(admin.from('supporter_accounts').select('total_cents').eq('donor_key', accountKey).single())).total_cents, 0);
  assert.equal((await submit(guest, null, hash)).error.code, '23505');
  const confirm = (id, amount = 1000, mode = false) => admin.rpc('confirm_crypto_donation', { p_donation_id: id, p_verified_amount_cents: amount, p_livemode: mode, p_reviewer: 'integration operator' });
  assert.ok((await confirm(cryptoId, 1000, true)).error);
  assert.ok((await confirm(cryptoId, 0)).error);
  assert.equal((await checked(admin.from('support_donations').select('review_status').eq('id', cryptoId).single())).review_status, 'pending_review');
  const confirmed = await Promise.all(Array.from({ length: 8 }, () => confirm(cryptoId)));
  assert.equal(confirmed.filter((r) => r.data === true).length, 1);
  for (const r of confirmed) assert.equal(r.error, null);
  assert.equal((await checked(admin.from('donations').select('*').eq('support_donation_id', cryptoId))).length, 1);
  assert.equal((await checked(admin.from('supporter_accounts').select('total_cents').eq('donor_key', accountKey).single())).total_cents, 1000);
  const signed = createClient(process.env.VITE_SUPABASE_URL, process.env.VITE_SUPABASE_ANON_KEY);
  const login = await signed.auth.signInWithPassword({ email: testUser.email, password });
  if (login.error) throw login.error;
  assert.ok((await signed.rpc('confirm_crypto_donation', { p_donation_id: cryptoId, p_verified_amount_cents: 99999, p_livemode: false, p_reviewer: 'forged' })).error);
  assert.ok((await anon.from('support_donations').insert({ amount_usd: 500, status: 'completed', review_status: 'confirmed' })).error);
  assert.deepEqual(await checked(anon.from('support_donations').select('donor_name,transaction_hash').eq('id', cryptoId)), []);
  const stripeId = await checked(admin.rpc('reserve_donation_checkout', { p_donor_key: accountKey, p_user_id: testUser.id, p_amount_cents: 500, p_livemode: false }));
  const signedSession = `cs_test_${randomUUID().replaceAll('-', '')}`;
  sessions.push(signedSession);
  await checked(admin.from('donation_checkouts').update({ stripe_session_id: signedSession, donor_name: 'Private Stripe Donor', public_recognition: false }).eq('id', stripeId));
  assert.equal((await fulfill(signedSession, `evt_${signedSession}`)).data, true);
  assert.equal((await checked(admin.from('supporter_accounts').select('total_cents').eq('donor_key', accountKey).single())).total_cents, 1500);
  assert.deepEqual(await checked(admin.from('user_usage_points').select('has_donated,total_donated_usd').eq('user_id', testUser.id).eq('ip_hash', 'verified_donor').single()), { has_donated: true, total_donated_usd: 15 });
  const guestCryptoId = await checked(submit(guest, null, '0x' + randomUUID().replaceAll('-', '').repeat(2)));
  cryptoIds.push(guestCryptoId);
  assert.equal((await confirm(guestCryptoId)).data, true);
  assert.deepEqual(await checked(admin.from('user_usage_points').select('*').eq('ip_hash', guest)), []);
  console.log('PASS: private metadata, consent, pending crypto review, due dates, duplicate/forged submissions, atomic manual credit, mixed Stripe/crypto totals, guest no-credit policy');
  console.log('PASS: concurrent/replayed fulfillment, rollback, cumulative totals, receipt and browser privilege boundaries');
} finally {
  if (cryptoIds.length) {
    await checked(admin.from('donations').delete().in('support_donation_id', cryptoIds));
    await checked(admin.from('support_donations').delete().in('id', cryptoIds));
  }
  if (testUser) {
    await checked(admin.from('donations').delete().eq('user_id', testUser.id));
    const deleted = await admin.auth.admin.deleteUser(testUser.id);
    if (deleted.error) throw deleted.error;
  }
  await checked(admin.from('stripe_payment_events').delete().in('checkout_id', (await checked(admin.from('donation_checkouts').select('id').eq('donor_key', guest))).map((r) => r.id)));
  await checked(admin.from('donations').delete().in('stripe_session_id', sessions));
  await checked(admin.from('donation_checkouts').delete().eq('donor_key', guest));
  await checked(admin.from('supporter_accounts').delete().eq('donor_key', guest));
  await checked(admin.from('user_usage_points').delete().eq('ip_hash', guest));
}
